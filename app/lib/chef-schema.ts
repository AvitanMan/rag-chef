import type { Recipe, RecipeMetadataMap } from "./recipe-types";

export const DEFAULT_CHEF_PROVIDER = "ollama" as const;
export const DEFAULT_OLLAMA_CHAT_MODEL = "qwen3.5:9b";
export const DEFAULT_OLLAMA_EMBED_MODEL = "nomic-embed-text";
export const DEFAULT_OPENAI_MODEL = "gpt-5.6-terra";

export type ChefProvider = "ollama" | "openai";

export type PantryItem = {
  name: string;
  quantity?: string | number;
  unit?: string;
};

export type ChefProfile = {
  allergies: string[];
  diet: string[];
  dislikes: string[];
  skillLevel?: string;
  budget?: string;
  equipment: string[];
  equipmentSpecified?: boolean;
};

export type RecipeIngredient = {
  name: string;
  measure: string;
};

export type RecipeSource = {
  name: string;
  url: string;
};

export type RecipeCandidate = {
  id: string;
  title: string;
  ingredients: RecipeIngredient[];
  instructions: string[];
  source: RecipeSource;
  sourceUrl: string;
  summary?: string;
  tags: string[];
  allergens: string[];
  communityTips: string[];
  servings?: string | number;
  prepMinutes?: number;
  cookMinutes?: number;
  rating?: number;
  nutrition?: Record<string, string | number>;
};

export type ChefRequest = {
  query: string;
  pantry: PantryItem[];
  profile: ChefProfile;
  candidates: RecipeCandidate[];
  provider: ChefProvider;
  model?: string;
};

export type ChefSourceFact = {
  recipeId: string;
  fact: string;
  evidenceId?: string;
};

export type ChefChange = {
  recipeId: string;
  change: string;
  reason: string;
};

export type ChefRecommendation = {
  recipeId: string;
  reason: string;
  matchReason?: string;
  pantryMatch: string[];
  missingIngredients: string[];
};

export type ChefCitation = {
  recipeId: string;
  title: string;
  sourceName: string;
  sourceUrl: string;
};

export type ChefStructuredAnswer = {
  answer: string;
  sourceFacts: ChefSourceFact[];
  chefChanges: ChefChange[];
  recommendations: ChefRecommendation[];
  citations: ChefCitation[];
  warnings: string[];
};

export type RankedRecipe = {
  recipeId: string;
  score: number;
  pantryScore: number;
  semanticScore: number | null;
};

export type ChefApiResponse = ChefStructuredAnswer & {
  recipes: Recipe[];
  metadataByRecipeId: RecipeMetadataMap;
  outcome: "matches" | "no_match" | "constraints_unsatisfied" | "catalog_empty";
  generation: "ai" | "catalog_fallback";
  provider: ChefProvider;
  model: string;
  timings: { retrievalMs: number; generationMs: number; totalMs: number };
  retrieval: {
    method: "precomputed_embeddings" | "lexical_pantry" | "catalog_order" | "empty";
    catalogCount: number;
    embedModel: string;
    ranked: RankedRecipe[];
    allergyExcludedCount: number;
    sourceExcludedCount: number;
  };
};

